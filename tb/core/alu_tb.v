`timescale 1ns/1ps
`default_nettype none

`include "../../rtl/common/rv32i_defs.vh"

//==============================================================
// Module      : alu_tb
// Project     : FPGA RISC-V SoC with SHA-256 Accelerator
// Description :
//   Self-checking verification environment for the RV32I ALU.
//
// Features:
//   - Directed testing
//   - PASS / FAIL reporting
//   - Zero flag verification
//   - Waveform generation
//   - Final verification summary
//
//==============================================================

module alu_tb;

    //----------------------------------------------------------
    // Parameters
    //----------------------------------------------------------

    parameter DATA_WIDTH = 32;

    //----------------------------------------------------------
    // DUT Signals
    //----------------------------------------------------------

    reg  [DATA_WIDTH-1:0] operand_a;
    reg  [DATA_WIDTH-1:0] operand_b;

    reg  [3:0] alu_op;

    wire [DATA_WIDTH-1:0] result;
    wire                  zero;

    //----------------------------------------------------------
    // Statistics
    //----------------------------------------------------------

    integer errors;
    integer tests;

    //----------------------------------------------------------
    // Device Under Test
    //----------------------------------------------------------

    alu DUT (

        .operand_a (operand_a),
        .operand_b (operand_b),

        .alu_op    (alu_op),

        .result    (result),
        .zero      (zero)

    );

    //----------------------------------------------------------
    // Waveform Dump
    //----------------------------------------------------------

    initial begin

        $dumpfile("sim/alu/alu.vcd");
        $dumpvars(0, alu_tb);

    end;

    //----------------------------------------------------------
    // Initialize Counters
    //----------------------------------------------------------

    initial begin

        errors = 0;
        tests  = 0;

    end

    //----------------------------------------------------------
    // Verification Task
    //----------------------------------------------------------

    task check_operation;

        input [DATA_WIDTH-1:0] a;
        input [DATA_WIDTH-1:0] b;

        input [3:0] operation;

        input [DATA_WIDTH-1:0] expected_result;
        input                  expected_zero;

    begin

        operand_a = a;
        operand_b = b;
        alu_op    = operation;

        #1;

        tests = tests + 1;

        //------------------------------------------------------
        // Result Check
        //------------------------------------------------------

        if(result !== expected_result) begin

            $display("[FAIL] Result");

            $display("        Operand A : %h", a);
            $display("        Operand B : %h", b);
            $display("        ALU Op    : %b", operation);

            $display("        Expected  : %h", expected_result);
            $display("        Received  : %h", result);

            errors = errors + 1;

        end

        else begin

            $display("[PASS] Result");

        end

        //------------------------------------------------------
        // Zero Flag Check
        //------------------------------------------------------

        if(zero !== expected_zero) begin

            $display("[FAIL] Zero Flag");

            $display("        Expected : %b", expected_zero);
            $display("        Received : %b", zero);

            errors = errors + 1;

        end

        else begin

            $display("[PASS] Zero Flag");

        end

        $display("");

    end

    endtask

    //----------------------------------------------------------
    // Test Sequence
    //----------------------------------------------------------

    initial begin

        $display("");
        $display("=================================================");
        $display("          RV32I ALU Verification");
        $display("=================================================");
        $display("");
            //------------------------------------------------------
        // Arithmetic Operations
        //------------------------------------------------------

        $display("-----------------------------------------------");
        $display("Testing Arithmetic Operations");
        $display("-----------------------------------------------");
        $display("");

        //------------------------------------------------------
        // ADD : Simple Addition
        //------------------------------------------------------

        check_operation(
            32'd10,
            32'd20,
            `ALU_ADD,
            32'd30,
            1'b0
        );

        //------------------------------------------------------
        // ADD : Zero Result
        //------------------------------------------------------

        check_operation(
            32'd0,
            32'd0,
            `ALU_ADD,
            32'd0,
            1'b1
        );

        //------------------------------------------------------
        // ADD : Overflow Check
        //------------------------------------------------------
        // NOTE:
        // RV32I ALU does not generate an overflow flag.
        // The expected behavior is natural 32-bit wraparound.
        //------------------------------------------------------

        check_operation(
            32'hFFFFFFFF,
            32'h00000001,
            `ALU_ADD,
            32'h00000000,
            1'b1
        );

        //------------------------------------------------------
        // SUB : Simple Subtraction
        //------------------------------------------------------

        check_operation(
            32'd20,
            32'd10,
            `ALU_SUB,
            32'd10,
            1'b0
        );

        //------------------------------------------------------
        // SUB : Zero Result
        //------------------------------------------------------

        check_operation(
            32'd25,
            32'd25,
            `ALU_SUB,
            32'd0,
            1'b1
        );

        //------------------------------------------------------
        // SUB : Negative Result
        //------------------------------------------------------

        check_operation(
            32'd10,
            32'd20,
            `ALU_SUB,
            32'hFFFFFFF6,
            1'b0
        );

        //------------------------------------------------------
        // Logical Operations
        //------------------------------------------------------

        $display("-----------------------------------------------");
        $display("Testing Logical Operations");
        $display("-----------------------------------------------");
        $display("");

        //------------------------------------------------------
        // AND
        //------------------------------------------------------

        check_operation(
            32'hF0F0F0F0,
            32'hFFFF0000,
            `ALU_AND,
            32'hF0F00000,
            1'b0
        );

        //------------------------------------------------------
        // AND : All Ones
        //------------------------------------------------------

        check_operation(
            32'hFFFFFFFF,
            32'hFFFFFFFF,
            `ALU_AND,
            32'hFFFFFFFF,
            1'b0
        );

        //------------------------------------------------------
        // AND : All Zeros
        //------------------------------------------------------

        check_operation(
            32'hAAAAAAAA,
            32'h55555555,
            `ALU_AND,
            32'h00000000,
            1'b1
        );

        //------------------------------------------------------
        // OR
        //------------------------------------------------------

        check_operation(
            32'hF0F00000,
            32'h0000F0F0,
            `ALU_OR,
            32'hF0F0F0F0,
            1'b0
        );

        //------------------------------------------------------
        // OR : All Zeros
        //------------------------------------------------------

        check_operation(
            32'h00000000,
            32'h00000000,
            `ALU_OR,
            32'h00000000,
            1'b1
        );

        //------------------------------------------------------
        // XOR
        //------------------------------------------------------

        check_operation(
            32'hAAAAAAAA,
            32'h55555555,
            `ALU_XOR,
            32'hFFFFFFFF,
            1'b0
        );

        //------------------------------------------------------
        // XOR : Same Inputs
        //------------------------------------------------------

        check_operation(
            32'h12345678,
            32'h12345678,
            `ALU_XOR,
            32'h00000000,
            1'b1
        );

        //------------------------------------------------------
        // XOR : Mixed Pattern
        //------------------------------------------------------

        check_operation(
            32'hFFFF0000,
            32'h00FFFF00,
            `ALU_XOR,
            32'hFF00FF00,
            1'b0
        );

                //------------------------------------------------------
        // Shift Operations
        //------------------------------------------------------

        $display("-----------------------------------------------");
        $display("Testing Shift Operations");
        $display("-----------------------------------------------");
        $display("");

        //------------------------------------------------------
        // SLL : Shift Left Logical
        //------------------------------------------------------

        check_operation(
            32'h00000001,
            32'd4,
            `ALU_SLL,
            32'h00000010,
            1'b0
        );

        //------------------------------------------------------
        // SLL : Shift by Zero
        //------------------------------------------------------

        check_operation(
            32'h12345678,
            32'd0,
            `ALU_SLL,
            32'h12345678,
            1'b0
        );

        //------------------------------------------------------
        // SLL : Shift by 31
        //------------------------------------------------------

        check_operation(
            32'h00000001,
            32'd31,
            `ALU_SLL,
            32'h80000000,
            1'b0
        );

        //------------------------------------------------------
        // SRL : Shift Right Logical
        //------------------------------------------------------

        check_operation(
            32'h80000000,
            32'd4,
            `ALU_SRL,
            32'h08000000,
            1'b0
        );

        //------------------------------------------------------
        // SRL : Shift by Zero
        //------------------------------------------------------

        check_operation(
            32'h87654321,
            32'd0,
            `ALU_SRL,
            32'h87654321,
            1'b0
        );

        //------------------------------------------------------
        // SRL : Shift by 31
        //------------------------------------------------------

        check_operation(
            32'h80000000,
            32'd31,
            `ALU_SRL,
            32'h00000001,
            1'b0
        );

        //------------------------------------------------------
        // SRA : Positive Number
        //------------------------------------------------------

        check_operation(
            32'h00000020,
            32'd2,
            `ALU_SRA,
            32'h00000008,
            1'b0
        );

        //------------------------------------------------------
        // SRA : Negative Number
        //------------------------------------------------------

        check_operation(
            32'hFFFFFFF0,
            32'd2,
            `ALU_SRA,
            32'hFFFFFFFC,
            1'b0
        );

        //------------------------------------------------------
        // SRA : Shift by Zero
        //------------------------------------------------------

        check_operation(
            32'hFFFFFF80,
            32'd0,
            `ALU_SRA,
            32'hFFFFFF80,
            1'b0
        );

        //------------------------------------------------------
        // Comparison Operations
        //------------------------------------------------------

        $display("-----------------------------------------------");
        $display("Testing Comparison Operations");
        $display("-----------------------------------------------");
        $display("");

        //------------------------------------------------------
        // SLT : True
        //------------------------------------------------------

        check_operation(
            32'd5,
            32'd10,
            `ALU_SLT,
            32'd1,
            1'b0
        );

        //------------------------------------------------------
        // SLT : False
        //------------------------------------------------------

        check_operation(
            32'd20,
            32'd10,
            `ALU_SLT,
            32'd0,
            1'b1
        );

        //------------------------------------------------------
        // SLT : Signed Comparison
        // (-1 < 1)
        //------------------------------------------------------

        check_operation(
            32'hFFFFFFFF,
            32'h00000001,
            `ALU_SLT,
            32'd1,
            1'b0
        );

        //------------------------------------------------------
        // SLTU : Unsigned Comparison
        //------------------------------------------------------

        check_operation(
            32'd5,
            32'd10,
            `ALU_SLTU,
            32'd1,
            1'b0
        );

        //------------------------------------------------------
        // SLTU : False
        //------------------------------------------------------

        check_operation(
            32'd20,
            32'd10,
            `ALU_SLTU,
            32'd0,
            1'b1
        );

        //------------------------------------------------------
        // SLTU : Unsigned Difference
        //------------------------------------------------------
        // 0xFFFFFFFF > 1 (unsigned)
        //------------------------------------------------------

        check_operation(
            32'hFFFFFFFF,
            32'h00000001,
            `ALU_SLTU,
            32'd0,
            1'b1
        );

        //------------------------------------------------------
        // PASS_B
        //------------------------------------------------------

        check_operation(
            32'h12345678,
            32'hCAFEBABE,
            `ALU_PASS_B,
            32'hCAFEBABE,
            1'b0
        );

        //------------------------------------------------------
        // PASS_B : Zero
        //------------------------------------------------------

        check_operation(
            32'hFFFFFFFF,
            32'h00000000,
            `ALU_PASS_B,
            32'h00000000,
            1'b1
        );

                //------------------------------------------------------
        // Verification Summary
        //------------------------------------------------------

        $display("");
        $display("=================================================");
        $display("           ALU Verification Summary");
        $display("=================================================");
        $display("");

        $display("Total Tests Executed : %0d", tests);
        $display("Total Errors         : %0d", errors);
        $display("");

        if (errors == 0) begin

            $display("***********************************************");
            $display("*                                             *");
            $display("*       ALL TESTS PASSED SUCCESSFULLY!        *");
            $display("*                                             *");
            $display("***********************************************");

        end

        else begin

            $display("***********************************************");
            $display("*                                             *");
            $display("*      VERIFICATION FAILED!                   *");
            $display("*                                             *");
            $display("*      Errors Detected : %0d                  *", errors);
            $display("*                                             *");
            $display("***********************************************");

        end

        $display("");
        $display("=================================================");
        $display("            End of Verification");
        $display("=================================================");
        $display("");

        $finish;

    end

endmodule

`default_nettype wire